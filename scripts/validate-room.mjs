import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { STATIONS } from '../src/content/stations.js';
import { isWalkable, detectRoom, FURNITURE_COLLIDERS } from '../src/content/world-logic.js';

const raw=readFileSync(new URL('../public/models/sala-1.glb',import.meta.url));
assert.equal(raw.toString('ascii',0,4),'glTF','Sala 1 must be glTF binary');
assert.equal(raw.readUInt32LE(4),2,'glTF v2');
assert.equal(raw.readUInt32LE(8),raw.byteLength,'GLB declared file length');
const len=raw.readUInt32LE(12);
assert.equal(raw.toString('ascii',16,20),'JSON');
const gltf=JSON.parse(raw.subarray(20,20+len).toString('utf8'));
assert.ok(gltf.meshes?.length>0,'room mesh exists');
assert.ok(gltf.materials?.length>0,'room material exists');
assert.ok(gltf.images?.length>0,'room texture exists');
const accessor=gltf.accessors.find(a=>a.type==='VEC3' && a.min && a.max);
assert.ok(accessor,'room position bounds exist');
const scale=5.55;
const width=(accessor.max[0]-accessor.min[0])*scale;
const depth=(accessor.max[2]-accessor.min[2])*scale;
assert.ok(width<7.5 && depth<6.7,`room interior fit ${width}x${depth}`);
assert.ok(isWalkable(-9,-4.65),'station 01 entrance should be free');
assert.equal(isWalkable(-9,-6.35),false,'imported central console collider');
assert.ok(isWalkable(-11,-7.25),'left aisle beside console is open');
assert.ok(isWalkable(-7,-7.25),'right aisle beside console is open');
assert.equal(detectRoom(-11,-7.25),'systems','accessible side aisle counts as Systems Room');
assert.equal(STATIONS[0].id,'systems');
assert.equal(FURNITURE_COLLIDERS.length,1);
console.log('PASS supplied Sala 1 GLB, texture, bounding fit, entrance clearance, central console and accessible aisles');
